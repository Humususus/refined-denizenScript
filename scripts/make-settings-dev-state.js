// Writes media/settings/dev-state.js: a `state` message built from package.json's defaults by the
// compiled settings model (run tsc first), for media/settings/dev.html -- the browser harness used
// to check the page against the mockup. Neither file ships (.vscodeignore).
//
//   node scripts/make-settings-dev-state.js

const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const model = require(path.join(root, 'out', 'settings', 'settingsModel.js'));
const { baseTagSpecialColors } = require(path.join(root, 'out', 'highlight', 'denizenHighlighter.js'));

const props = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).contributes.configuration.properties;
const def = key => props[key] && props[key].default;

const opts = { headerSymbols: def('denizenscript.header_symbols'), doInlineColors: true, displayDarkColors: false, tagSpecialColors: baseTagSpecialColors, colorRef: {} };
const colors = {};
for (const card of model.COLOR_CARDS) {
    colors[card.type] = Object.assign(model.parsePaletteValue(def(`denizenscript.theme_colors.${card.type}`) || ''), { overridden: false });
}
const options = {};
for (const card of model.OPTION_CARDS) {
    options[card.key] = { value: def(model.optionSettingId(card.key)), overridden: false };
}
const state = Object.assign({
    kind: 'state',
    paletteOn: true,
    colors,
    options,
    colorMap: model.parseColorMap(def('denizenscript.theme_colors.text_color_map')),
    colorMapOverridden: false,
    cards: model.cardSpans(opts),
    cardInfo: model.COLOR_CARDS,
    optionInfo: model.OPTION_CARDS,
    // Review Focus 1 of R6: a user upgrading with legacy string sources, one of them an add-on's.
    sources: model.sourcesState([
        'https://github.com/Energobro/DenizenM-Tjtoxshpilivili1/archive/refs/heads/master.zip',
        'https://my.fork/x.zip',
    ], [], false),
    sourcesOverridden: false,
    metaStatusLine: model.metaStatusLine({
        loadedAt: Date.now() - 2 * 3600 * 1000,
        sources: Array.from({ length: 6 }, (_, i) => ({ url: 'u' + i, state: 'unchanged', blocks: 1 })),
        commands: 200, tags: 900, events: 114, mechanisms: 50,
    }, Date.now()),
    metaLoadedAt: 1,
}, model.previewState(opts));

fs.writeFileSync(path.join(root, 'media', 'settings', 'dev-state.js'), '// Generated by scripts/make-settings-dev-state.js\nwindow.DEV_STATE = ' + JSON.stringify(state, null, 1) + ';\n');
console.log('wrote media/settings/dev-state.js');
